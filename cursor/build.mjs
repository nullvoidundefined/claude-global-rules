// --- agents, commands, skills ----------------------------------------------------

function loadAgents() {
  const agents = [];
  for (const entry of readdirSync(join(ROOT, "agents")).sort()) {
    if (!entry.endsWith(".md")) continue;
    const { frontmatter, body } = splitFrontmatter(readSource(`agents/${entry}`));
    const fields = parseFrontmatter(frontmatter);
    if (!fields.name || !fields.description) throw new Error(`agents/${entry}: name and description are required`);
    agents.push({ file: entry, fields, body });
  }
  return agents;
}

function buildAgents(agents) {
  const files = {};
  for (const { file, fields, body } of agents) {
    const tools = typeof fields.tools === "string" ? fields.tools.split(",").map((tool) => tool.trim()) : [];
    const readonly = !tools.some((tool) => tool === "Write" || tool === "Edit");
    files[`agents/${file}`] = renderFrontmatterFile(
      { name: fields.name, description: fields.description, model: "inherit", readonly: readonly ? "true" : "false" },
      `agents/${file}`,
      body,
    );
  }
  return files;
}

