function buildAll() {
  const hooksConfig = JSON.parse(readSource("cursor/hooks.json"));
  if (hooksConfig.version !== 1) throw new Error("cursor/hooks.json: version must be 1");
  const { names: ported, events: portedEvents } = portedHookNames(hooksConfig);
  const agents = loadAgents();
  return {
    "rules/000-global-rules.mdc": buildGlobalRules(ported),
    "rules/001-session-types.mdc": buildSessionTypes(),
    "rules/002-global-memory-index.mdc": buildGlobalMemoryIndex(),
    ...buildStackRules(),
    ...buildRulebookReference(),
    ...buildTier2Rules(),
    "rules/structure-conventions.mdc": buildStructureConventions(),
    "rules/cloud-deployment.mdc": buildCloudDeployment(),
    ...buildAgents(agents),
    ...buildCommands(agents),
    ...buildSkills(),
    "PORT-STATUS.md": buildPortStatus(hooksConfig, portedEvents),
  };
}

function listGeneratedOnDisk() {
  const found = [];
  const walk = (dir) => {
    if (!existsSync(dir)) return;
    for (const entry of readdirSync(dir)) {
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) walk(full);
      else if (readFileSync(full, "utf8").includes(GENERATED_PREFIX)) found.push(relative(OUT_DIR, full));
    }
  };
  for (const sub of ["rules", "agents", "commands", "skills"]) walk(join(OUT_DIR, sub));
  if (existsSync(join(OUT_DIR, "PORT-STATUS.md"))) found.push("PORT-STATUS.md");
  return found;
}

function main() {
  const mode = process.argv[2] ?? "--check";
  const files = buildAll();
  const stale = listGeneratedOnDisk().filter((path) => !(path in files));
  if (mode === "--print") {
    for (const path of Object.keys(files).sort()) console.log(path);
    return;
  }
  if (mode === "--write") {
    for (const [path, content] of Object.entries(files)) {
      const full = join(OUT_DIR, path);
      mkdirSync(dirname(full), { recursive: true });
      writeFileSync(full, content);
    }
    for (const path of stale) rmSync(join(OUT_DIR, path));
    console.log(`cursor/build.mjs: wrote ${Object.keys(files).length} files${stale.length ? `, removed ${stale.length} stale` : ""}`);
    return;
  }
  if (mode !== "--check") throw new Error(`unknown mode ${mode}; use --check, --write, or --print`);
  const drift = [];
  for (const [path, content] of Object.entries(files)) {
    const full = join(OUT_DIR, path);
    if (!existsSync(full) || readFileSync(full, "utf8") !== content) drift.push(path);
  }
  drift.push(...stale.map((path) => `${path} (stale)`));
  if (drift.length > 0) {
    console.error(`cursor/build.mjs --check: ${drift.length} file(s) out of date, run: node cursor/build.mjs --write\n  ${drift.join("\n  ")}`);
    process.exit(1);
  }
  console.log(`cursor/build.mjs --check: ${Object.keys(files).length} files in sync`);
}

main();
