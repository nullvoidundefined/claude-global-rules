// --- helpers -----------------------------------------------------------------

function readSource(relativePath) {
  return readFileSync(join(ROOT, relativePath), "utf8");
}

function splitFrontmatter(text) {
  if (!text.startsWith("---\n")) return { frontmatter: null, body: text };
  const end = text.indexOf("\n---\n", 4);
  if (end === -1) return { frontmatter: null, body: text };
  return { frontmatter: text.slice(4, end), body: text.slice(end + 5) };
}

function parseFrontmatter(frontmatter) {
  const fields = {};
  let currentKey = null;
  for (const line of (frontmatter ?? "").split("\n")) {
    const keyValue = line.match(/^([A-Za-z_-]+):\s*(.*)$/);
    if (keyValue) {
      currentKey = keyValue[1];
      fields[currentKey] = keyValue[2].trim() === "" ? [] : keyValue[2].trim();
      continue;
    }
    const item = line.match(/^\s*-\s*"?([^"]*?)"?\s*$/);
    if (item && currentKey && Array.isArray(fields[currentKey])) fields[currentKey].push(item[1]);
  }
  return fields;
}

function substitute(text, substitutions, sourceName) {
  let result = text;
  for (const [needle, replacement] of substitutions) {
    if (!result.includes(needle)) {
      throw new Error(`${sourceName}: expected text not found, update cursor/build.mjs: ${JSON.stringify(needle)}`);
    }
    result = result.split(needle).join(replacement);
  }
  return result;
}

function generatedMarker(sourceName) {
  return `${GENERATED_PREFIX}${sourceName}. Do not edit; change the source and run: node cursor/build.mjs --write -->`;
}

// Cursor's .mdc frontmatter is parsed loosely; a colon or a quote inside the
// description is the one thing known to break it, so neither is emitted.
function cleanDescription(text) {
  return text.replace(/\s+/g, " ").replace(/:/g, " -").replace(/"/g, "'").trim();
}

function renderRule({ description, globs = "", alwaysApply = false }, sourceName, body) {
  return [
    "---",
    `description: ${cleanDescription(description)}`,
    globs ? `globs: ${globs}` : "globs:",
    `alwaysApply: ${alwaysApply ? "true" : "false"}`,
    "---",
    generatedMarker(sourceName),
    "",
    body.trim(),
    "",
  ].join("\n");
}

function renderFrontmatterFile(fields, sourceName, body) {
  const lines = ["---"];
  for (const [key, value] of Object.entries(fields)) lines.push(`${key}: ${value}`);
  lines.push("---", generatedMarker(sourceName), "", body.trim(), "");
  return lines.join("\n");
}

function portedHookNames(hooksConfig) {
  const names = new Set();
  const events = {};
  for (const [event, entries] of Object.entries(hooksConfig.hooks)) {
    for (const entry of entries) {
      const parts = entry.command.trim().split(/\s+/);
      if (parts[0] !== ADAPTER) throw new Error(`hooks.json: ${event} command does not start with ${ADAPTER}`);
      if (parts[1] !== event) throw new Error(`hooks.json: ${event} entry passes event "${parts[1]}" to the adapter`);
      for (const name of parts.slice(2)) {
        if (!existsSync(join(ROOT, "hooks", `${name}.sh`))) throw new Error(`hooks.json: ${event} names hooks/${name}.sh, which does not exist`);
        names.add(name);
        (events[name] ??= []).push(event);
      }
    }
  }
  return { names, events };
}

function annotateEnforcerTags(body, ported) {
  return body.replace(/\[([^\]\n]*)\]$/gm, (whole, inner) =>
    `[${inner.replace(/hook:([a-z0-9-]+)/g, (tag, name) => (ported.has(name) ? tag : `${tag} in Claude Code; manual in Cursor`))}]`,
  );
}

