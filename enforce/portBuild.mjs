export function loadStackConventions() {
  const rulesDir = join(ROOT, "rules");
  const conventions = [];
  for (const entry of readdirSync(rulesDir).sort()) {
    if (!entry.endsWith(".md") || entry === "session-types.md") continue;
    const name = entry.replace(/\.md$/, "");
    const linkPath = join(rulesDir, entry);
    const sourcePath = resolveSymlink(linkPath);
    const { frontmatter, body } = splitFrontmatter(readFileSync(linkPath, "utf8"));
    const fields = parseFrontmatter(frontmatter);
    if (!Array.isArray(fields.paths) || fields.paths.length === 0) throw new Error(`rules/${entry}: no paths: frontmatter`);
    conventions.push({ name, paths: fields.paths, body, sourceName: relative(ROOT, sourcePath) });
  }
  return conventions;
}

function resolveSymlink(path) {
  try {
    return resolve(dirname(path), readlinkSync(path));
  } catch {
    return path;
  }
}

export function loadAgents() {
  const agents = [];
  for (const entry of readdirSync(join(ROOT, "agents")).sort()) {
    if (!entry.endsWith(".md")) continue;
    const { frontmatter, body } = splitFrontmatter(readSource(`agents/${entry}`));
    const fields = parseFrontmatter(frontmatter);
    if (!fields.name || !fields.description) throw new Error(`agents/${entry}: name and description are required`);
    const tools = typeof fields.tools === "string" ? fields.tools.split(",").map((tool) => tool.trim()) : [];
    agents.push({ file: entry, fields, body, writes: tools.some((tool) => tool === "Write" || tool === "Edit") });
  }
  return agents;
}

