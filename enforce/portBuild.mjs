export const MANIFEST_NAME = ".claude-port.json";

// The GitHub repository the ports are generated from, for the generated README.
export const SOURCE_REPO = "https://github.com/nullvoidundefined/claude-global-rules";

// An allowlist .gitignore: the target directory is also where the tool keeps
// its own state (Cursor's extensions and MCP config, Codex's auth.json,
// sessions, and logs), none of which may ever reach a repository. Only the
// generated files are tracked, so even `git add -A` stays safe.
export function renderAllowlistGitignore(paths) {
  const allowed = new Set([".gitignore", MANIFEST_NAME]);
  for (const path of paths) {
    const segments = path.split("/");
    for (let depth = 1; depth <= segments.length; depth += 1) {
      const prefix = segments.slice(0, depth).join("/");
      allowed.add(depth < segments.length ? `${prefix}/` : prefix);
    }
  }
  return [
    "# Generated by the port build. Everything the tool itself writes here stays",
    "# local; only the generated port is tracked. Do not edit by hand.",
    "*",
    ...[...allowed].sort().map((entry) => `!/${entry}`),
    "",
  ].join("\n");
}

