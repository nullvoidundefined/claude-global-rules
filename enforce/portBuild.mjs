export function loadSkills() {
  const skills = [];
  for (const entry of readdirSync(join(ROOT, "skills")).sort()) {
    const skillPath = join(ROOT, "skills", entry, "SKILL.md");
    if (!existsSync(skillPath)) continue;
    const { frontmatter, body } = splitFrontmatter(readFileSync(skillPath, "utf8"));
    const usesShellInclude = body.includes("```!");
    const override = SKILL_OVERRIDES[entry];
    if (usesShellInclude && !override) throw new Error(`skills/${entry}: uses a shell include the ports cannot run; add a SKILL_OVERRIDES entry in enforce/portBuild.mjs`);
    if (!usesShellInclude && override) throw new Error(`skills/${entry}: no longer needs its SKILL_OVERRIDES entry; remove it`);
    const fields = parseFrontmatter(frontmatter);
    if (!fields.name || !fields.description) throw new Error(`skills/${entry}: name and description are required`);
    skills.push({ name: entry, fields, body: override ?? body, sourceName: `skills/${entry}/SKILL.md` });
  }
  return skills;
}

export function loadSettingsHookRows() {
  const settings = JSON.parse(readSource("settings.json"));
  const rows = [];
  for (const [event, groups] of Object.entries(settings.hooks)) {
    for (const group of groups) {
      for (const hook of group.hooks) {
        rows.push({
          event,
          matcher: group.matcher ?? "",
          name: basename(hook.command).replace(/\.sh$/, ""),
          timeout: hook.timeout,
          statusMessage: hook.statusMessage,
          conditional: hook.if,
        });
      }
    }
  }
  return { settings, rows };
}

