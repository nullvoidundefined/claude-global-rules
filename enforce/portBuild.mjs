/**
 * portBuild.mjs: what the cursor/ and openai/ port builds share.
 *
 * Both ports render the same canonical sources (CLAUDE.md, the CLAUDE-*.md
 * convention files, rulebook/, rules/session-types.md, global-memory/INDEX.md,
 * skills/, agents/, settings.json) into tool-specific shapes. This module
 * holds the source loaders, the substitution primitive, the skill overrides,
 * the shared command bodies, and the --check / --write / --print driver, so
 * the two build scripts contain only what differs between the tools.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, readlinkSync, rmSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const GENERATED_PREFIX = "<!-- GENERATED by ";

export function generatedMarker(builder, sourceName) {
  return `${GENERATED_PREFIX}${builder} from ${sourceName}. Do not edit; change the source and run: node ${builder} --write -->`;
}

export function readSource(relativePath) {
  return readFileSync(join(ROOT, relativePath), "utf8");
}

export function splitFrontmatter(text) {
  if (!text.startsWith("---\n")) return { frontmatter: null, body: text };
  const end = text.indexOf("\n---\n", 4);
  if (end === -1) return { frontmatter: null, body: text };
  return { frontmatter: text.slice(4, end), body: text.slice(end + 5) };
}

export function parseFrontmatter(frontmatter) {
  const fields = {};
  let currentKey = null;
  for (const line of (frontmatter ?? "").split("\n")) {
    const keyValue = line.match(/^([A-Za-z_-]+):\s*(.*)$/);
    if (keyValue) {
      currentKey = keyValue[1];
      fields[currentKey] = keyValue[2].trim() === "" ? [] : keyValue[2].trim();
      continue;
    }
    const item = line.match(/^\s*-\s*"?([^"]*?)"?\s*$/);
    if (item && currentKey && Array.isArray(fields[currentKey])) fields[currentKey].push(item[1]);
  }
  return fields;
}

// Every tool-specific rewrite goes through here with a needle that must still
// exist in the source, so a source edit that moves the sentence fails the
// build with the needle it could not find instead of emitting stale prose.
export function substitute(text, substitutions, sourceName) {
  let result = text;
  for (const [needle, replacement] of substitutions) {
    if (!result.includes(needle)) {
      throw new Error(`${sourceName}: expected text not found, update the port build: ${JSON.stringify(needle)}`);
    }
    result = result.split(needle).join(replacement);
  }
  return result;
}

export function currentR001Line(source) {
  const match = /^R-001: .*$/m.exec(source);
  if (!match) throw new Error("CLAUDE.md: no R-001 line found");
  return match[0];
}

// Rewrites the [hook:X] enforcer tags at the end of each norm line: a hook the
// port runs keeps its tag, one it cannot run is labelled so the rule is known
// to depend on recall under that tool.
export function annotateEnforcerTags(body, portedHookNames, toolName) {
  return body.replace(/\[([^\]\n]*)\]$/gm, (whole, inner) =>
    `[${inner.replace(/hook:([a-z0-9-]+)/g, (tag, name) => (portedHookNames.has(name) ? tag : `${tag} in Claude Code; manual in ${toolName}`))}]`,
  );
}

